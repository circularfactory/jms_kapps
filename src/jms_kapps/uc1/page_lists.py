"""The three lists of UC1's page, Operations, Learned values and Measured positions, each from one
SPARQL query whose text the page shows, so that a person can run it on the same dataset and get the
same rows.

**Operations** lists each unscrewing operation with its Screw, the resource that issued it, its
status, its outcome, the reason of a failed one, and the resource that decided the outcome. The
deciding one is found along the provenance chain that the anomaly detector commits with each
decision: the operation was classified with a parameter copy (the values it used), the copy was
generated by a classification, and the classification's agent decided. An operation that was never
classified has no copy, so its row has no outcome and no deciding resource, and its reason says why.

**Learned values** lists each Screw type's maximum dynamic torque, the one threshold the learner
refines: the value now, from the latest read, and the value at the run's start, from the first
read that found a Screw type. So the reads start after the seed, before which the dataset still holds the
previous run's values; the learner commits nothing before the first press.

**Measured positions** (interim title) lists each measured position that the anomaly detector saved
as an uncertainty quantification: a Screw's head position, and the approach end position of an
unscrewing operation, each with its best estimate, the Gaussian-mixture literal of its random
variable, and the standard deviation, the square root of the variance that the literal holds.

Each query is standard SPARQL 1.1: it declares its own prefixes, and names no graph and calls no
function that only one store knows, so it runs unchanged in the store's workbench and in any other
SPARQL endpoint on the dataset. It asks for no inferred statement: each pattern is one that a
participant writes itself.

**The queries run in a background read, never on a page poll.** `PageLists` sends each once at
its start and then every second, whether a page is open or not, and keeps what they answered;
the page renders that, so a page that polls adds no store request. It keeps the text of each
query exactly as it handed it to the store, and the page shows that text. A read that fails keeps
the rows the last one read, and says why.
"""

from __future__ import annotations

import math
import re
import threading
from collections.abc import Callable
from datetime import UTC, datetime

from kapps_semantic_middleware.vocabulary import SVC, SVC_NS
from kapps_triplestore_interface import IRI
from pydantic import BaseModel

from jms_kapps.common.supervision import WATCH_INTERVAL_SECONDS
from jms_kapps.common.triplestore import Queryable, bindings
from jms_kapps.uc1.uncertainty import MalformedMixture, read_measurement
from jms_kapps.uc1.vocabulary import JMS, JMS_NS, PROV, PROV_NS, UQ, UQ_NS

# The prefixes the queries declare for themselves, so that they need none of the dataset's: the
# names the seed registers in the dataset, and PROV-O's usual one.
_PREFIXES = {"uns": JMS_NS, "svc": SVC_NS, "prov": PROV_NS, "uq": UQ_NS}


def _term(iri: IRI) -> str:
    """`iri` as a query writes it: by one of its own prefixes."""
    for prefix, namespace in _PREFIXES.items():
        if str(iri).startswith(namespace):
            return f"{prefix}:{str(iri).removeprefix(namespace)}"
    raise ValueError(f"the queries declare no prefix for {iri}")


def _declared(*prefixes: str) -> str:
    return "".join(f"PREFIX {prefix}: <{_PREFIXES[prefix]}>\n" for prefix in prefixes)


# The query of Operations, exactly as the page's background read sends it.
OPERATIONS = (
    _declared("uns", "svc", "prov")
    + f"""
# Each unscrewing operation, with its Screw, the resource that issued it, its status,
# its outcome, the reason of a failed one, and the resource that decided the outcome:
# the agent of the classification that generated the values the operation used.
SELECT ?operation ?screw ?issuer ?status ?outcome ?reason ?decidedBy WHERE {{
  ?operation a {_term(JMS.UnscrewingOperation)} .
  OPTIONAL {{ ?operation {_term(JMS.concernsScrew)} ?screw }}
  OPTIONAL {{ ?operation {_term(SVC.issuedBy)} ?issuer }}
  OPTIONAL {{ ?operation {_term(SVC.hasOperationStatus)} ?status }}
  OPTIONAL {{ ?operation {_term(JMS.hasDetectionResult)} ?outcome }}
  OPTIONAL {{ ?operation {_term(SVC.hasExecutionResult)} ?reason }}
  OPTIONAL {{
    ?operation {_term(JMS.classifiedWith)} ?values .
    ?values {_term(PROV.wasGeneratedBy)} ?classification .
    ?classification {_term(PROV.wasAssociatedWith)} ?decidedBy .
  }}
}}
ORDER BY ?screw ?operation
"""
)

# The query of Learned values, exactly as the page's background read sends it.
LEARNED_VALUES = (
    _declared("uns")
    + f"""
# Each Screw type's maximum dynamic torque, the threshold that the learner refines.
SELECT ?screwType ?maxDynamicTorque WHERE {{
  ?screwType a {_term(JMS.ScrewType)} ;
             {_term(JMS.hasMaxDynamicTorque)} ?maxDynamicTorque .
}}
ORDER BY ?screwType
"""
)

# What a row of Measured positions calls the position it shows.
SCREW_HEAD_POSITION = "screw-head position"
APPROACH_END_POSITION = "approach end position"

# The query of Measured positions, exactly as the page's background read sends it.
MEASURED_POSITIONS = (
    _declared("uns", "uq")
    + f"""
# Each measured position saved as an uncertainty quantification: the head position of a Screw
# and the approach end position of an unscrewing operation, each with its best estimate and the
# literal of its random variable.
SELECT ?subject ?position ?estimate ?literal WHERE {{
  {{
    ?subject {_term(JMS.hasMeasuredScrewHeadPosition)} ?estimate ;
             {_term(JMS.hasScrewHeadPositionVariable)} ?variable .
    BIND("{SCREW_HEAD_POSITION}" AS ?position)
  }} UNION {{
    ?subject {_term(JMS.hasMeasuredApproachEndPosition)} ?estimate ;
             {_term(JMS.hasApproachEndPositionVariable)} ?variable .
    BIND("{APPROACH_END_POSITION}" AS ?position)
  }}
  ?variable {_term(UQ.hasDistribution)} ?literal .
}}
ORDER BY ?subject ?position
"""
)


def local_name(iri: str) -> str:
    """The part of `iri` after its last `#` or `/`, or `iri` itself if that is empty: for a
    person to read only."""
    return re.split(r"[#/]", iri)[-1] or iri


class OperationRow(BaseModel):
    """One row of Operations. The operation, its Screw and its outcome by their local names, as a
    person reads them; the issuer and the deciding resource by their IRIs, which the page matches
    to the processes of the run. Each is None where the operation has none."""

    operation: str
    screw: str | None
    issuer: str | None
    status: str | None
    outcome: str | None
    reason: str | None
    decided_by: str | None


class LearnedValue(BaseModel):
    """One row of Learned values: a Screw type by its local name, its maximum dynamic torque now,
    and the one that the first read to find a Screw type found, each as the store writes it.
    `at_start` is None for a type that that read did not find."""

    screw_type: str
    now: str
    at_start: str | None


class MeasuredPositionRow(BaseModel):
    """One row of Measured positions: the Screw or the operation by its local name, which position
    it is, its best estimate as the store writes it, the standard deviation that the literal holds
    (None where the literal does not parse as one measurement), and the literal's lexical form."""

    subject: str
    position: str
    estimate: str
    standard_deviation: str | None
    literal: str


class ShownList[Row: BaseModel](BaseModel):
    """What the page shows of one list.

    `query` is the text of the latest read, exactly as it was handed to the store, and None before
    the first. `rows` are the rows of the latest read that succeeded, in the query's order, and
    `read_at` is when that read was sent (UTC, ISO 8601), None before one has succeeded. `error`
    says why the latest read failed, and is None when it succeeded.
    """

    query: str | None = None
    rows: list[Row] = []
    read_at: str | None = None
    error: str | None = None


class Lists(BaseModel):
    """The three lists, as the latest reads left them."""

    operations: ShownList[OperationRow] = ShownList[OperationRow]()
    learned_values: ShownList[LearnedValue] = ShownList[LearnedValue]()
    measured_positions: ShownList[MeasuredPositionRow] = ShownList[MeasuredPositionRow]()


def _value(row: dict, name: str) -> str | None:
    """The lexical value of `name` in one row of SPARQL's JSON results, or None if unbound."""
    return str(row[name]["value"]) if name in row else None


def _named(row: dict, name: str) -> str | None:
    found = _value(row, name)
    return None if found is None else local_name(found)


def _operation(row: dict) -> OperationRow:
    return OperationRow(
        operation=local_name(str(row["operation"]["value"])),
        screw=_named(row, "screw"),
        issuer=_value(row, "issuer"),
        status=_value(row, "status"),
        outcome=_named(row, "outcome"),
        reason=_value(row, "reason"),
        decided_by=_value(row, "decidedBy"),
    )


def _standard_deviation(literal: str) -> str | None:
    """The standard deviation of the one measurement that `literal` holds, or None where it holds
    none that parses."""
    try:
        _, variance = read_measurement(literal)
    except MalformedMixture:
        return None
    return f"{math.sqrt(variance):g}" if variance >= 0 else None


def _measured_position(row: dict) -> MeasuredPositionRow:
    literal = str(row["literal"]["value"])
    return MeasuredPositionRow(
        subject=local_name(str(row["subject"]["value"])),
        position=str(row["position"]["value"]),
        estimate=str(row["estimate"]["value"]),
        standard_deviation=_standard_deviation(literal),
        literal=literal,
    )


class PageLists:
    """Operations, Learned values and Measured positions, read from `store` in the background.

    Args:
        store: The store of the run's dataset: anything that answers a SPARQL query as a store
            does.
        interval: How long the background read waits between two reads, in seconds: as long as
            the supervisor's watch waits between two reads of the services.
    """

    def __init__(
        self, store: Queryable, *, interval: float = WATCH_INTERVAL_SECONDS
    ) -> None:
        self._store = store
        self._interval = interval
        self._lock = threading.Lock()
        self._last = Lists()
        # Each Screw type's value as the first read to find one found it, by its local name.
        self._at_start: dict[str, str] | None = None
        # Set while no background read runs: at a stop, and before the first start.
        self._stopped: threading.Event | None = None

    def last(self) -> Lists:
        """What the latest reads found. Sends nothing."""
        with self._lock:
            return self._last

    def read(self) -> None:
        """Send the three queries once, and keep what each answered, or why it failed: a read that
        fails keeps the rows the last one read. It raises nothing, so that the background read
        goes on whatever the store does."""
        operations = self._read(OPERATIONS, lambda rows: [_operation(r) for r in rows])
        learned = self._read(LEARNED_VALUES, self._learned)
        measured = self._read(
            MEASURED_POSITIONS, lambda rows: [_measured_position(r) for r in rows]
        )
        with self._lock:
            self._last = Lists(
                operations=operations(self._last.operations),
                learned_values=learned(self._last.learned_values),
                measured_positions=measured(self._last.measured_positions),
            )

    def _read[Row: BaseModel](
        self, query: str, rows_of: Callable[[list[dict]], list[Row]]
    ) -> Callable[[ShownList[Row]], ShownList[Row]]:
        """Send `query`, and return how the list it fills changes: to its new rows, or to the
        last ones with why the read failed."""
        sent_at = datetime.now(UTC).isoformat()
        try:
            rows = rows_of(bindings(self._store, query, convert=False))
        # Whatever the store raises: it is shown on the page, and read again.
        except Exception as error:  # noqa: BLE001
            why = str(error) or type(error).__name__
            return lambda last: last.model_copy(update={"query": query, "error": why})
        return lambda last: type(last)(query=query, rows=rows, read_at=sent_at)

    def _learned(self, rows: list[dict]) -> list[LearnedValue]:
        found = {
            local_name(str(row["screwType"]["value"])): str(row["maxDynamicTorque"]["value"])
            for row in rows
        }
        # The first read that finds a Screw type: one of a dataset that holds none yet sets
        # nothing.
        if self._at_start is None and found:
            self._at_start = found
        return [
            LearnedValue(screw_type=name, now=now, at_start=(self._at_start or {}).get(name))
            for name, now in found.items()
        ]

    def start(self) -> None:
        """Read at once, and then every interval, on a daemon thread, until `stop`. A start
        while the reads run changes nothing."""
        with self._lock:
            if self._stopped is not None and not self._stopped.is_set():
                return
            stopped = self._stopped = threading.Event()

        def read_until_stopped() -> None:
            while not stopped.is_set():
                self.read()
                stopped.wait(self._interval)

        threading.Thread(target=read_until_stopped, name="uc1-page-lists", daemon=True).start()

    def stop(self) -> None:
        """Stop the background read: no read starts after this. One under way finishes, and
        keeps what it read."""
        with self._lock:
            if self._stopped is not None:
                self._stopped.set()
